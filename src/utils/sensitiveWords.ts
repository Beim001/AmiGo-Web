// 含拉丁字母的词（如 US、SS、CN）只按整词匹配：前后不能紧挨其他英文字母，
// 避免 Augustus、Russell 等正常名字被误判；中日韩词与纯数字词仍按子串匹配。
const escapeRegExp = (str: string) => str.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const containsWord = (text: string, word: string): boolean => {
  if (!/[A-Z]/.test(word)) return text.includes(word);
  return new RegExp(`(?<![A-Z])${escapeRegExp(word)}(?![A-Z])`).test(text);
};

// 角色昵称敏感词与规则校验函数
export const validatePlayerName = (name: string): { valid: boolean; reason?: string; category?: string; word?: string } => {
  const trimmed = name.trim();

  // 1. 长度校验
  if (trimmed.length < 2) {
    return { valid: false, reason: '角色昵称至少需要 2 个字符' };
  }
  if (trimmed.length > 10) {
    return { valid: false, reason: '角色昵称长度不能超过 10 个字符' };
  }

  // 2. 空格与不可见字符校验
  if (/\s/.test(name) || /[\u200B-\u200D\uFEFF]/.test(name)) {
    return { valid: false, reason: '角色昵称包含空格或不可见特殊字符' };
  }

  // 3. 纯特殊符号校验
  if (/^[^\w\u4e00-\u9fa5]+$/.test(trimmed)) {
    return { valid: false, reason: '角色昵称不能全为特殊符号' };
  }

  // 4. 敏感词匹配（同时进行原串匹配与去除符号后的二次防绕过匹配）
  const normalized = trimmed.toUpperCase();
  const strippedNormalized = normalized.replace(/[^\w\u4e00-\u9fa5\u3040-\u30ff\uac00-\ud7af]/g, '');

  for (const group of SENSITIVE_WORDS_CONFIG) {
    for (const word of group.words) {
      const targetWord = word.toUpperCase();
      const strippedTarget = targetWord.replace(/[^\w\u4e00-\u9fa5\u3040-\u30ff\uac00-\ud7af]/g, '');

      if (
        containsWord(normalized, targetWord) ||
        (strippedTarget.length > 0 && containsWord(strippedNormalized, strippedTarget))
      ) {
        return {
          valid: false,
          reason: `包含受限或违规词汇 [${word}] (${group.category})`,
          category: group.category,
          word: word
        };
      }
    }
  }

  return { valid: true };
};
